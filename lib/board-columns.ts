// Завершающий столбец доски задач («Выполнено», «Готово», «Done»…): как «Оплачен» у сделок —
// задача, перенесённая в него, выполнена, а вынесенная обратно снова открыта. Без базы: нужно и в браузере
const FINAL = /^(выполнено|выполнены|готово|сделано|завершено|завершены|закрыто|done|completed)$/i;

export const isFinalColumn = (name: string) => FINAL.test(name.trim());
